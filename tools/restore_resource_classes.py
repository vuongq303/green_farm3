#!/usr/bin/env python3
"""Generate SDK R aliases while leaving AGP in charge of actual resource IDs.

JADX exported old APK IDs, which are not stable after linking resources again.
Use public.xml as the identity map and retain SDK styleable arrays and indices:
their order is part of the SDK's typed-array contract (and gameplay constants).
"""

from __future__ import annotations

import argparse
from pathlib import Path
import re
import xml.etree.ElementTree as ET


APP_PACKAGE = "com.gameloft.android.ANMP.GloftGF2F"
TARGET_APP_PACKAGE = "com.quanhoang.greenfarm3"
SDK_PACKAGES = (
    "com.facebook",
    "com.google.android.gms.ads",
    "com.google.android.gms.ads.impl",
    "com.google.firebase.messaging",
)
RESOURCE_LITERAL = re.compile(r"\b0[xX]7[fF][0-9a-fA-F]{6}\b")


def java_resource_name(name: str) -> str:
    """Apply aapt's resource-name escaping, including dotted style names."""
    return name.replace(".", "_").replace("-", "_").replace(":", "_")


def read_public_resources(path: Path, app_package: str = APP_PACKAGE) -> dict[int, str]:
    result: dict[int, str] = {}
    for entry in ET.parse(path).getroot().findall("public"):
        value = int(entry.attrib["id"], 0)
        reference = (
            f"{app_package}.R.{entry.attrib['type']}."
            f"{java_resource_name(entry.attrib['name'])}"
        )
        if value in result and result[value] != reference:
            raise ValueError(f"Conflicting resource identity for {value:#x}")
        result[value] = reference
    return result


def render_alias(source: str, resources: dict[int, str], package: str,
                 app_package: str = APP_PACKAGE) -> str:
    if package not in SDK_PACKAGES:
        raise ValueError(f"Not an SDK alias package: {package}")
    if not re.search(rf"^package {re.escape(package)};", source, re.MULTILINE):
        raise ValueError(f"Unexpected package in source for {package}")

    def replace_id(match: re.Match[str]) -> str:
        value = int(match.group(), 16)
        if value not in resources:
            raise ValueError(f"Unmapped resource ID {match.group()} in {package}.R")
        return resources[value]

    # Non-resource integers are styleable offsets; deliberately do not change them.
    generated = RESOURCE_LITERAL.sub(replace_id, source)
    # JADX also emitted symbolic app-R references inside SDK styleable arrays.
    # Change only that fully qualified resource owner; array order/indices and
    # android.R/SDK resource identities are still the original contract.
    generated = re.sub(r'\b' + re.escape(APP_PACKAGE) + r'\.R\.', app_package + '.R.', generated)
    generated = re.sub(
        r"^(\s*)public final class (\w+) \{",
        lambda match: match.group() if match.group(2) == "R" else
        f"{match.group(1)}public static final class {match.group(2)} {{",
        generated,
        flags=re.MULTILINE,
    )
    return "// Generated by tools/restore_resource_classes.py; do not edit.\n" + generated


def selected_app_package(project_root: Path) -> str:
    return TARGET_APP_PACKAGE if (project_root / 'app/src/main/java'
            / TARGET_APP_PACKAGE.replace('.', '/')).is_dir() else APP_PACKAGE


def generate(project_root: Path, output: Path) -> list[Path]:
    app_package = selected_app_package(project_root)
    resources = read_public_resources(project_root / "app/src/main/res/values/public.xml", app_package)
    # Validate everything before writing, so a bad/missing source cannot leave a
    # partly generated set that appears ready for compilation.
    rendered = []
    for package in SDK_PACKAGES:
        relative = Path(*package.split(".")) / "R.java"
        source = project_root / "app/src/main/java" / relative
        rendered.append((output / relative, render_alias(source.read_text(), resources, package, app_package)))
    for path, content in rendered:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
    return [path for path, _ in rendered]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project-root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    output = args.output or args.project_root / "app/build/generated/restored-java"
    paths = generate(args.project_root, output)
    print(f"Generated {len(paths)} SDK resource alias classes in {output}")


if __name__ == "__main__":
    main()
