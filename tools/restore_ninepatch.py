#!/usr/bin/env python3
"""Reconstruct source borders of APK-compiled nine-patches without changing pixels.

JADX exports compiled PNGs, whose npTc chunk contains the stretch divisions and
content padding normally encoded in a source .9.png's one-pixel border. AAPT2
expects that source border. This tool copies the resource tree into a generated
directory and reconstructs only those PNGs containing npTc. Original resources
are never modified. No Pillow or other third-party dependency is needed.

Only non-interlaced 8-bit PNGs are supported; fail instead of guessing for
any other compiled nine-patch. Compiled npTc/npOl metadata is regenerated by AAPT2
from the exact content pixels and restored border. npLb optical layout bounds
are not supported; fail if encountered rather than silently discard them.
"""

import argparse
import binascii
from pathlib import Path
import shutil
import struct
import subprocess
import tempfile
import zlib


PNG_SIGNATURE = b"\x89PNG\r\n\x1a\n"
TRANSPARENT = b"\0\0\0\0"
BLACK = b"\0\0\0\xff"


def png_chunks(data):
    if not data.startswith(PNG_SIGNATURE):
        raise ValueError("not a PNG")
    offset = len(PNG_SIGNATURE)
    chunks = []
    while offset < len(data):
        length, = struct.unpack_from(">I", data, offset)
        kind = data[offset + 4:offset + 8]
        payload = data[offset + 8:offset + 8 + length]
        if len(payload) != length or offset + 12 + length > len(data):
            raise ValueError("truncated PNG chunk")
        crc, = struct.unpack_from(">I", data, offset + 8 + length)
        if binascii.crc32(kind + payload) & 0xffffffff != crc:
            raise ValueError("PNG CRC mismatch")
        chunks.append((kind, payload))
        offset += 12 + length
        if kind == b"IEND":
            return chunks
    raise ValueError("PNG missing IEND")


def rgba_pixels(chunks):
    header = next(payload for kind, payload in chunks if kind == b"IHDR")
    width, height, depth, color, compression, filtering, interlace = struct.unpack(
        ">IIBBBBB", header)
    if (depth, compression, filtering, interlace) != (8, 0, 0, 0) or color not in (0, 2, 3, 4, 6):
        raise ValueError("only non-interlaced 8-bit PNGs are supported")
    if color != 3 and any(k == b"tRNS" for k, _ in chunks):
        raise ValueError("non-paletted tRNS transparency is not supported")
    channels = {0: 1, 2: 3, 3: 1, 4: 2, 6: 4}[color]
    raw = zlib.decompress(b"".join(p for k, p in chunks if k == b"IDAT"))
    stride = width * channels
    if len(raw) != (stride + 1) * height:
        raise ValueError("unexpected PNG pixel length")
    rows = []
    previous = bytearray(stride)
    for y in range(height):
        start = y * (stride + 1)
        filter_type = raw[start]
        row = bytearray(raw[start + 1:start + 1 + stride])
        for x in range(stride):
            left = row[x - channels] if x >= channels else 0
            above = previous[x]
            upper_left = previous[x - channels] if x >= channels else 0
            if filter_type == 0:
                predictor = 0
            elif filter_type == 1:
                predictor = left
            elif filter_type == 2:
                predictor = above
            elif filter_type == 3:
                predictor = (left + above) // 2
            elif filter_type == 4:
                p = left + above - upper_left
                distances = (abs(p - left), abs(p - above), abs(p - upper_left))
                predictor = (left, above, upper_left)[distances.index(min(distances))]
            else:
                raise ValueError("unknown PNG row filter")
            row[x] = (row[x] + predictor) & 255
        if color == 6:
            rows.append(bytes(row))
        elif color == 4:
            rows.append(b"".join(bytes((g, g, g, a)) for g, a in zip(row[::2], row[1::2])))
        elif color == 2:
            rows.append(b"".join(row[x:x + 3] + b"\xff" for x in range(0, len(row), 3)))
        elif color == 0:
            rows.append(b"".join(bytes((g, g, g, 255)) for g in row))
        else:
            palette = next(p for k, p in chunks if k == b"PLTE")
            alpha = next((p for k, p in chunks if k == b"tRNS"), b"")
            rows.append(b"".join(palette[index * 3:index * 3 + 3]
                                  + bytes((alpha[index] if index < len(alpha) else 255,))
                                  for index in row))
        previous = row
    return width, height, rows


def patch_metadata(chunks, width, height):
    if any(k == b"npLb" for k, _ in chunks):
        raise ValueError("npLb optical layout bounds require additional recovery")
    patches = [p for k, p in chunks if k == b"npTc"]
    if len(patches) != 1:
        raise ValueError("expected one npTc chunk")
    patch = patches[0]
    if len(patch) < 32:
        raise ValueError("truncated npTc header")
    _, nx, ny, nc = patch[:4]
    if nx == 0 or ny == 0 or nx % 2 or ny % 2:
        raise ValueError("invalid nine-patch division counts")
    if len(patch) != 32 + 4 * (nx + ny + nc):
        raise ValueError("unexpected npTc length")
    # Android serializes division and padding values in network byte order.
    # The three offset fields at 4, 8 and 28 are not needed for reconstruction.
    left, right, top, bottom = struct.unpack_from(">4i", patch, 12)
    x_divs = struct.unpack_from(">" + "i" * nx, patch, 32)
    y_divs = struct.unpack_from(">" + "i" * ny, patch, 32 + 4 * nx)
    for divisions, limit in ((x_divs, width), (y_divs, height)):
        if list(divisions) != sorted(set(divisions)):
            raise ValueError("nine-patch divisions are not strictly increasing")
        if divisions[0] < 0 or divisions[-1] > limit:
            raise ValueError("nine-patch division out of bounds")
    if min(left, right, top, bottom) < 0 or left + right >= width or top + bottom >= height:
        raise ValueError("unsupported or invalid content padding")
    return x_divs, y_divs, (left, right, top, bottom)


def png_chunk(kind, payload):
    return (struct.pack(">I", len(payload)) + kind + payload
            + struct.pack(">I", binascii.crc32(kind + payload) & 0xffffffff))


def encode_rgba(width, height, rows):
    header = struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0)
    raw = b"".join(b"\0" + row for row in rows)
    return (PNG_SIGNATURE + png_chunk(b"IHDR", header)
            + png_chunk(b"IDAT", zlib.compress(raw, 9)) + png_chunk(b"IEND", b""))


def reconstruct(data):
    chunks = png_chunks(data)
    width, height, rows = rgba_pixels(chunks)
    x_divs, y_divs, padding = patch_metadata(chunks, width, height)
    left, right, top, bottom = padding
    output = [bytearray(TRANSPARENT * (width + 2)) for _ in range(height + 2)]
    for y, row in enumerate(rows):
        output[y + 1][4:-4] = row

    def mark(x, y):
        output[y][x * 4:x * 4 + 4] = BLACK

    for start, end in zip(x_divs[::2], x_divs[1::2]):
        for x in range(start, end):
            mark(x + 1, 0)
    for start, end in zip(y_divs[::2], y_divs[1::2]):
        for y in range(start, end):
            mark(0, y + 1)
    for x in range(left, width - right):
        mark(x + 1, height + 1)
    for y in range(top, height - bottom):
        mark(width + 1, y + 1)
    result = encode_rgba(width + 2, height + 2, output)
    # Check the actual serialized output, not just the in-memory source rows.
    ow, oh, restored = rgba_pixels(png_chunks(result))
    if (ow, oh) != (width + 2, height + 2) or [r[4:-4] for r in restored[1:-1]] != rows:
        raise ValueError("reconstruction changed interior pixels")
    return result


def verify_compilation(original, restored, aapt2):
    before = png_chunks(original.read_bytes())
    with tempfile.TemporaryDirectory(prefix="ninepatch-aapt2-") as directory:
        subprocess.run([str(aapt2), "compile", str(restored), "-o", directory], check=True)
        flat_files = list(Path(directory).glob("*.flat"))
        if len(flat_files) != 1:
            raise ValueError("AAPT2 did not produce one compiled resource")
        flat = flat_files[0].read_bytes()
        signature_offset = flat.find(PNG_SIGNATURE)
        if signature_offset < 0:
            raise ValueError("AAPT2 output contains no compiled PNG")
        after = png_chunks(flat[signature_offset:])
        old_w, old_h, old_rows = rgba_pixels(before)
        new_w, new_h, new_rows = rgba_pixels(after)
        if (old_w, old_h, old_rows) != (new_w, new_h, new_rows):
            raise ValueError("AAPT2 recompilation changed interior pixels")
        if patch_metadata(before, old_w, old_h) != patch_metadata(after, new_w, new_h):
            raise ValueError("AAPT2 recompilation changed stretch divisions or padding")
        old_outline = [p for k, p in before if k == b"npOl"]
        new_outline = [p for k, p in after if k == b"npOl"]
        if old_outline != new_outline:
            raise ValueError("AAPT2 recompilation changed outline metadata")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, help="Original res directory (read only)")
    parser.add_argument("output", type=Path, help="Generated res directory (replaced)")
    parser.add_argument("--verify-aapt2", type=Path, help="Compile and compare all restored nine-patches")
    args = parser.parse_args()
    source, output = args.source.resolve(), args.output.resolve()
    if not source.is_dir() or source == output or source in output.parents or output in source.parents:
        # A normal app/build output is a sibling of src, never a child of source.
        raise ValueError("source and generated output must be separate resource trees")
    if output.exists():
        shutil.rmtree(output)
    shutil.copytree(source, output)
    restored = 0
    for original in sorted(source.rglob("*.9.png")):
        data = original.read_bytes()
        if not any(k == b"npTc" for k, _ in png_chunks(data)):
            continue
        generated = output / original.relative_to(source)
        generated.write_bytes(reconstruct(data))
        if args.verify_aapt2:
            verify_compilation(original, generated, args.verify_aapt2.resolve())
        restored += 1
    mode = " (AAPT2 round-trip verified)" if args.verify_aapt2 else ""
    print(f"Restored {restored} compiled nine-patches{mode}; original resources unchanged.")


if __name__ == "__main__":
    main()
